def _extract_answer_code(text):
    if text is None:
        return None
    text = text.strip().lower()
    if not text:
        return None

    first_char = text[0]

    if first_char in ("a", "b", "c", "а", "б", "в", "с"):
        if first_char in ("а", "a"):
            return "a"
        if first_char in ("б", "b"):
            return "b"
        if first_char in ("в", "с", "c"):
            return "c"

    return None


def calculate_16pf_scores(participant_id):
    scores = defaultdict(int)
    answers = (
        Answer.query
        .join(Questions, Questions.id == Answer.question_id)
        .filter(Answer.participant_id == participant_id)
        .all()
    )

    matched = 0
    for answer in answers:
        if not answer.question:
            continue
        try:
            qid = int(answer.question.kattell_id)
        except (TypeError, ValueError):
            continue

        key = CATTELL_KEY.get(qid)
        if not key:
            continue

        ans = _extract_answer_code(answer.answered_text)
        if ans is None:
            continue

        if ans not in key:
            continue

        factor, value = key[ans]
        scores[factor] += value
        matched += 1

    return dict(scores)


def convert_raw_to_sten(raw_scores):
    sten_scores = {}
    all_factors = ['A', 'B', 'C', 'E', 'F', 'G', 'H', 'I', 'L', 'M', 'N', 'O', 'Q1', 'Q2', 'Q3', 'Q4']

    for factor in all_factors:
        raw = raw_scores.get(factor, 0)
        norms = STEN_NORMS.get(factor, [])
        sten = 1
        for s, min_val, max_val in norms:
            if min_val <= raw <= max_val:
                sten = s
                break
        sten_scores[factor] = sten


    return sten_scores


